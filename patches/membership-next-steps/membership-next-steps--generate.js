/*
 * Builds generated membership-next-steps artifacts from the page source
 * (single source of truth: Membership Next Steps HTML.html + CSS.css).
 *
 *   node patches/membership-next-steps/membership-next-steps--generate.js
 *
 * `guard:membership-next-steps` requires this module and recomputes
 * everything, so an artifact edited by hand — or a source edited without
 * regenerating — fails `npm run guard` deterministically.
 *
 * History that shaped the split (from /tour-confirmation/, 2026-08-20):
 * Thrive Custom HTML pastes truncate at ~32KB, and WordPress post content
 * entity-encodes stray ampersands on output (&& becomes &#038;&#038;)
 * which breaks inline JS — so the page's JS lives in WPCode.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const PAGE_DIR = path.join(ROOT, 'Website', 'Pages', 'Memberships (Category)', 'membership-next-steps');
const HTML_SOURCE = path.join(PAGE_DIR, 'Membership Next Steps HTML.html');
const CSS_SOURCE = path.join(PAGE_DIR, 'Membership Next Steps CSS.css');
const OUT_DIR = __dirname;
const THRIVE_CAP = 32 * 1024;

function build() {
  const html = fs.readFileSync(HTML_SOURCE, 'utf8').replace(/\r\n/g, '\n');
  const css = fs.readFileSync(CSS_SOURCE, 'utf8').replace(/\r\n/g, '\n').trim();

  const splitAt = html.indexOf('<script>');
  if (splitAt === -1) throw new Error('No <script> found in page source.');

  let markup = html.slice(0, splitAt).replace(/\s+$/, '') + '\n';
  const scripts = html.slice(splitAt);

  if (!/<\/div>\s*$/.test(markup)) throw new Error('Markup does not end with </div> — split boundary moved?');

  const blocks = [...scripts.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1].trim());
  if (blocks.length < 2) throw new Error('Expected 2 script blocks, found ' + blocks.length);
  blocks.forEach(b => { new Function(b); });

  const guarded = blocks.map(b => b.replace(/('use strict';)/, "$1\n  if (!document.getElementById('se-mn-page')) return;"));
  guarded.forEach((g, i) => {
    if (g.indexOf("getElementById('se-mn-page')") === -1) throw new Error('block ' + i + ' did not take the page guard');
    new Function(g);
  });

  const wpcodeJs = "/* Membership next-steps page JS — WPCode snippet (site-wide footer, guarded).\n" +
    " * GENERATED from the script blocks in\n" +
    " * Website/Pages/Memberships (Category)/membership-next-steps/Membership Next Steps HTML.html\n" +
    " * by patches/membership-next-steps/membership-next-steps--generate.js — edit the page\n" +
    " * source, then regenerate and re-paste; guard:membership-next-steps fails on drift.\n" +
    " * WHY WPCode and not inline: WordPress content filters entity-encode\n" +
    " * stray ampersands in post content on output (&& becomes &#038;&#038;),\n" +
    " * which is a syntax error. WPCode injects raw. Discovered 2026-08-20.\n" +
    " * Each IIFE no-ops unless #se-mn-page exists on the page. */\n\n" + guarded.join('\n\n');

  const pasteMarkup = markup.replace(/\s*<link rel="stylesheet" href="Membership Next Steps CSS\.css">\s*/g, '\n');

  const header1 = '<!-- Thrive paste 1/2: PAGE MARKUP for /membership-next-steps/. Regenerated by patches/membership-next-steps/membership-next-steps--generate.js — edit the page source, not this file. Paste 2/2 (scripts) is superseded by the WPCode page snippet: WordPress entity-encodes inline JS. -->\n';
  const headerG = '<!-- Gutenberg paste for /membership-next-steps/: markup block, then CSS in a second html block wrapped in <style>. Regenerated by patches/membership-next-steps/membership-next-steps--generate.js — edit the page source, not this file. Page JS is a separate WPCode snippet. -->\n';

  const gutenberg = headerG + '<!-- wp:html -->\n' + pasteMarkup.trim() + '\n<!-- /wp:html -->\n\n<!-- wp:html -->\n<style>\n' + css + '\n</style>\n<!-- /wp:html -->\n';

  return {
    'membership-next-steps--paste-into-thrive-markup.html': header1 + pasteMarkup,
    'membership-next-steps--paste-into-gutenberg.html': gutenberg,
    'membership-next-steps--paste-into-wpcode-page.js': wpcodeJs,
  };
}

module.exports = { build, OUT_DIR, THRIVE_CAP };

if (require.main === module) {
  const artifacts = build();
  for (const [name, content] of Object.entries(artifacts)) {
    const bytes = Buffer.byteLength(content, 'utf8');
    if (name.indexOf('paste-into-thrive-') !== -1 && bytes > THRIVE_CAP - 2048) {
      throw new Error(name + ' is ' + bytes + ' bytes — too close to the 32KB Thrive cap.');
    }
    fs.writeFileSync(path.join(OUT_DIR, name), content);
    console.log(name + ': ' + bytes + ' bytes');
  }
  console.log('all artifacts written; script blocks compile');
}
