#!/usr/bin/env node
/**
 * Mirrors CLAUDE.md into the rule files other agents, models and IDEs read.
 *
 * Run:  npm run rules:sync          (regenerate every mirror)
 *       npm run guard:agent-rules   (exit 1 if any mirror has drifted)
 *
 * Why one direction and not two
 * -----------------------------
 * The ask was "change one, the others follow". Implemented as: CLAUDE.md is the
 * source, every other file is generated from it, and a guard fails the moment
 * any of them stops matching.
 *
 * Two-way sync was deliberately not built. With several agents editing the same
 * tree at once, a bidirectional copier cannot tell an intentional edit from a
 * stale one, and the losing side is overwritten silently -- which is how the
 * 1,399 unpushed lines nearly went missing. This design cannot silently discard
 * anything: it refuses instead, and says which file to edit.
 *
 * So editing a MIRROR still works. It just fails loudly and tells you to move
 * the change into CLAUDE.md and re-run the sync, rather than quietly reverting
 * you on the next run.
 *
 * The mirrors are byte-identical to CLAUDE.md apart from a required header:
 * every agent gets the SAME rules, which was the point.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SOURCE_REL = 'CLAUDE.md';

/**
 * Each target: where it goes, and the header that must precede the mirrored
 * body. Add an entry here to cover another tool -- nothing else changes.
 */
const TARGETS = [
  {
    rel: 'AGENTS.md',
    what: 'generic agent instructions (Codex, Amp, Jules, and most CLI agents)',
    header: (hash) => [
      '<!-- GENERATED FROM CLAUDE.md — DO NOT EDIT THIS FILE. -->',
      '<!-- Edit CLAUDE.md, then run: npm run rules:sync -->',
      `<!-- source-sha256: ${hash} -->`,
      '',
    ].join('\n'),
  },
  {
    rel: path.join('.cursor', 'rules', 'southend.mdc'),
    what: 'Cursor project rules',
    header: (hash) => [
      '---',
      'description: South End Club repo — working rules for every agent',
      'alwaysApply: true',
      '---',
      '',
      '<!-- GENERATED FROM CLAUDE.md — DO NOT EDIT THIS FILE. -->',
      '<!-- Edit CLAUDE.md, then run: npm run rules:sync -->',
      `<!-- source-sha256: ${hash} -->`,
      '',
    ].join('\n'),
  },
  {
    rel: path.join('.github', 'copilot-instructions.md'),
    what: 'GitHub Copilot / VS Code',
    header: (hash) => [
      '<!-- GENERATED FROM CLAUDE.md — DO NOT EDIT THIS FILE. -->',
      '<!-- Edit CLAUDE.md, then run: npm run rules:sync -->',
      `<!-- source-sha256: ${hash} -->`,
      '',
    ].join('\n'),
  },
];

/** Line endings are normalised so the hash is stable across checkouts. */
function normalise(text) {
  return text.replace(/\r\n/g, '\n');
}

function sourceHash(body) {
  return crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
}

function render(target, body, hash) {
  return target.header(hash) + body;
}

function readSource() {
  const abs = path.join(REPO_ROOT, SOURCE_REL);
  if (!fs.existsSync(abs)) {
    console.error(`[agent-rules] ${SOURCE_REL} not found — nothing to mirror.`);
    process.exit(1);
  }
  const body = normalise(fs.readFileSync(abs, 'utf8'));
  return { body, hash: sourceHash(body) };
}

function check() {
  const { body, hash } = readSource();
  const problems = [];

  TARGETS.forEach((target) => {
    const abs = path.join(REPO_ROOT, target.rel);
    const label = target.rel.split(path.sep).join('/');

    if (!fs.existsSync(abs)) {
      problems.push(`${label} — missing (${target.what})`);
      return;
    }

    const actual = normalise(fs.readFileSync(abs, 'utf8'));
    const expected = render(target, body, hash);
    if (actual === expected) return;

    // Distinguish "source moved on" from "someone edited the mirror", because
    // the fix is different and only one of them risks losing work.
    const stamped = actual.match(/source-sha256: ([0-9a-f]+)/);
    if (stamped && stamped[1] !== hash) {
      problems.push(`${label} — stale: CLAUDE.md changed after this was generated`);
    } else {
      problems.push(`${label} — EDITED DIRECTLY: this file is generated, so the edit will be lost`);
    }
  });

  if (problems.length) {
    console.error('[agent-rules] FAILED — mirrors do not match CLAUDE.md:');
    problems.forEach((p) => console.error(`  - ${p}`));
    console.error('');
    console.error('  If CLAUDE.md is right:      npm run rules:sync');
    console.error('  If a MIRROR holds the new');
    console.error('  wording: move it into CLAUDE.md first, then npm run rules:sync.');
    console.error('  Never hand-edit a generated file — every agent must read the same rules.');
    process.exit(1);
  }

  console.log(`[agent-rules] OK — ${TARGETS.length} mirrors match CLAUDE.md (${hash})`);
}

function sync() {
  const { body, hash } = readSource();

  TARGETS.forEach((target) => {
    const abs = path.join(REPO_ROOT, target.rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, render(target, body, hash), 'utf8');
    console.log(`  wrote ${target.rel.split(path.sep).join('/')}  (${target.what})`);
  });

  console.log(`[agent-rules] synced ${TARGETS.length} mirrors from ${SOURCE_REL} (${hash})`);
}

function main() {
  if (process.argv.slice(2).includes('--check')) check();
  else sync();
}

if (require.main === module) {
  main();
}

module.exports = { TARGETS, render, sourceHash, normalise };
